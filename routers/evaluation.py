class UnifiedEvaluationResponse(BaseModel):
    user_id: int
    created_at: datetime
    evaluated_at: datetime
    company_information: int
    evaluation: UnifiedEvaluationResult
    token_usage: TokenUsage = Field(default_factory=TokenUsage)


_FEEDBACK_HEADING_PREFIXES = (
    "WHAT YOU'RE DOING WELL:",
    "WHAT YOU'RE DOING WELL —",
    "WHAT YOU'RE DOING WELL -",
    "WHAT'S HOLDING YOU BACK:",
    "WHAT'S HOLDING YOU BACK —",
    "WHAT'S HOLDING YOU BACK -",
)


def _strip_feedback_heading(text: str) -> str:
    """Remove legacy heading prefixes from strength/weakness body text."""
    trimmed = (text or "").strip()
    if not trimmed:
        return trimmed
    upper = trimmed.upper()
    for prefix in _FEEDBACK_HEADING_PREFIXES:
        if upper.startswith(prefix.upper()):
            return trimmed[len(prefix) :].strip()
    return trimmed


_AI_PROMPT_PATH = Path(__file__).resolve().parent.parent / "prompts" / "ai_prompt.md"
_AI_PROMPT_CACHE: Optional[str] = None


def _load_cor_insight_coach_rules() -> str:
    """Load FUSION coaching rules (AI-PROMPT.md) for unified insight generation."""
    global _AI_PROMPT_CACHE
    if _AI_PROMPT_CACHE is not None:
        return _AI_PROMPT_CACHE
    try:
        _AI_PROMPT_CACHE = _AI_PROMPT_PATH.read_text(encoding="utf-8").strip()
    except OSError as err:
        logger.warning("Could not read coaching rules at %s: %s", _AI_PROMPT_PATH, err)
        _AI_PROMPT_CACHE = (
            "You are a Human Performance Coach operating within the FUSION framework. "
            "Interpret assessment results; do not calculate scores. "
            "Focus on behaviors, habits, performance, development, and growth."
        )
    return _AI_PROMPT_CACHE


def _format_tier_block(label: str, block: PerformanceTierBlock) -> str:
    parts = []
    for tier_name in ("primary", "secondary", "tertiary"):
        items = getattr(block, tier_name, []) or []
        if not items:
            continue
        lines = []
        for idx, qa in enumerate(items, 1):
            lines.append(f"  {idx}. Q: {qa.question}\n     A: {qa.answer}")
        parts.append(f"{label} — {tier_name.upper()}:\n" + "\n".join(lines))
    return "\n\n".join(parts) if parts else f"{label}: (no answers provided)"


@router.post("/evaluate-unified", response_model=UnifiedEvaluationResponse, status_code=status.HTTP_200_OK)
async def evaluate_unified_cor(payload: UnifiedEvaluationRequest):
    """
    Unified COR insights: organization capabilities + all performance categories in one LLM call.
    """
    request_received_at = datetime.now(timezone.utc)
    created_at = payload.created_at
    if created_at is not None and created_at.tzinfo is None:
        created_at = created_at.replace(tzinfo=timezone.utc)
    if created_at is None:
        created_at = request_received_at

    try:
        if not settings.OPENAI_API_KEY or settings.OPENAI_API_KEY.strip() == "" or settings.OPENAI_API_KEY.startswith("sk-proj-..."):
            raise ValueError("OPENAI_API_KEY is not configured or is using a placeholder.")

        llm = ChatOpenAI(
            model="gpt-4o-mini",
            openai_api_key=settings.OPENAI_API_KEY,
            temperature=0.2,
            model_kwargs={"response_format": {"type": "json_object"}},
        )

        caps = payload.cor_organization_capabilities.model_dump()
        caps_lines = "\n".join(
            f"- {key.replace('_', ' ').title()}: {value if value is not None else 'N/A'}"
            for key, value in caps.items()
        )

        perf_sections = []
        for slug, block in payload.performance.items():
            title = slug.replace("_", " ").title()
            perf_sections.append(_format_tier_block(title, block))
        perf_data_str = "\n\n---\n\n".join(perf_sections) if perf_sections else "No performance data."

        category_keys = list(payload.performance.keys())
        category_json_hint = ", ".join(
            f'"{key}": {{"strength": "...", "weakness": "..."}}' for key in category_keys
        )

        db = get_vector_store()
        cor_perf_chunks = get_chunks_by_category(db, COR_PERFORMANCE_CATEGORY)
        if cor_perf_chunks:
            cor_perf_context = "\n---\n".join(cor_perf_chunks)
            logger.info(
                "Loaded %s COR Performance knowledge chunks for unified evaluation (user_id=%s)",
                len(cor_perf_chunks),
                payload.user_id,
            )
        else:
            cor_perf_context = "NO COR PERFORMANCE KNOWLEDGE FOUND IN VECTOR STORE."
            logger.info(
                "No COR Performance knowledge chunks found for unified evaluation (user_id=%s)",
                payload.user_id,
            )

        coach_rules = _load_cor_insight_coach_rules()

        prompt_template = ChatPromptTemplate.from_messages([
            ("system", "{coach_rules}"),
            ("user", """
You are generating unified COR™ insights. Scores are pre-calculated — do NOT recalculate or invent numeric scores.

COR Performance Knowledge Base (category: COR Performance — use ALL of this context when interpreting results):
{cor_perf_context}

COR Organization Capabilities (scores 0-5, pre-calculated):
{caps}

Performance by FUSION dimension (Primary = highest-weight questions, Secondary, Tertiary):
{performance}

Coaching instructions:
1. Apply the interpretation rules, reflection guidance, and tone requirements from the system prompt.
2. Use participant reflection answers as the primary personalization source.
3. Focus on relationships between scores and behavioral patterns — do not simply explain individual scores.
4. Write cor_organization_capabilities as one cohesive narrative (75-100 words) about alignment, accountability, communication, leadership, and execution — referencing the numeric scores and COR Performance knowledge.
5. For each performance category, provide plain feedback only (no headings or labels inside the text):
   - strength: 2-4 sentences (50-75 words) describing what the employee is doing well
   - weakness: 2-4 sentences (50-75 words) describing the greatest opportunity / what is holding them back
6. Write key_observation as an overall insight synthesis (100-150 words) connecting capabilities and performance patterns.
7. Write in English. Be constructive and specific. Do NOT prefix strength or weakness values with titles like "WHAT YOU'RE DOING WELL".
8. Use coaching tone: "Your responses suggest...", "You may benefit from...", "This pattern often appears when...", "Consider focusing on...".
9. Avoid diagnostic or clinical language.

Return ONLY raw JSON with this schema:
{{
  "cor_organization_capabilities": "<string>",
  "performance": {{
    {category_hint}
  }},
  "key_observation": "<string>"
}}
"""),
        ])

        evaluation_result: UnifiedEvaluationResult
        token_usage = TokenUsage()

        try:
            chain = prompt_template | llm
            with get_openai_callback() as cb:
                response = await chain.ainvoke({
                    "coach_rules": coach_rules,
                    "cor_perf_context": cor_perf_context,
                    "caps": caps_lines,
                    "performance": perf_data_str,
                    "category_hint": category_json_hint,
                })
            token_usage = _extract_token_usage(response)
            if token_usage.total_tokens <= 0 and cb.total_tokens > 0:
                token_usage = TokenUsage(
                    prompt_tokens=int(cb.prompt_tokens or 0),
                    completion_tokens=int(cb.completion_tokens or 0),
                    total_tokens=int(cb.total_tokens or 0),
                )

            eval_data = json.loads(response.content)
            perf_out: Dict[str, CategoryPerformanceFeedback] = {}
            raw_perf = eval_data.get("performance") or {}
            if isinstance(raw_perf, dict):
                for key in category_keys:
                    block = raw_perf.get(key) or {}
                    if not isinstance(block, dict):
                        block = {}
                    perf_out[key] = CategoryPerformanceFeedback(
                        strength=_strip_feedback_heading(
                            str(block.get("strength") or block.get("Strength") or "No feedback provided.")
                        ),
                        weakness=_strip_feedback_heading(
                            str(
                                block.get("weakness")
                                or block.get("Weak")
                                or block.get("improvements")
                                or "No feedback provided."
                            )
                        ),
                    )
            else:
                for key in category_keys:
                    perf_out[key] = CategoryPerformanceFeedback(
                        strength="No feedback provided.",
                        weakness="No feedback provided.",
                    )

            evaluation_result = UnifiedEvaluationResult(
                cor_organization_capabilities=str(
                    eval_data.get("cor_organization_capabilities")
                    or eval_data.get("cor_organization_capabilities_insight")
                    or "No capability insight provided."
                ),
                performance=perf_out,
                key_observation=str(eval_data.get("key_observation") or "No overall observation provided."),
            )
        except json.JSONDecodeError:
            logger.error("Failed to decode unified LLM response as JSON: %s", response.content)
            evaluation_result = UnifiedEvaluationResult(
                cor_organization_capabilities="Failed to process unified evaluation.",
                performance={
                    key: CategoryPerformanceFeedback(
                        strength="Failed to process evaluation.",
                        weakness="Invalid LLM output formatting.",
                    )
                    for key in category_keys
                },
                key_observation="An error occurred while parsing the AI evaluator response.",
            )
        except Exception as llm_err:
            logger.error("Unified LLM error for user_id=%s: %s", payload.user_id, str(llm_err))
            evaluation_result = UnifiedEvaluationResult(
                cor_organization_capabilities="Failed to evaluate.",
                performance={
                    key: CategoryPerformanceFeedback(
                        strength="Failed to evaluate.",
                        weakness=f"Internal LLM Error: {str(llm_err)}",
                    )
                    for key in category_keys
                },
                key_observation="Please contact system administrator for technical details.",
            )

        evaluated_at = datetime.now(timezone.utc)
        logger.info(
            "Unified evaluation completed for user_id=%s, tokens=%s",
            payload.user_id,
            token_usage.total_tokens,
        )

        return UnifiedEvaluationResponse(
            user_id=payload.user_id,
            created_at=created_at,
            evaluated_at=evaluated_at,
            company_information=payload.company_information,
            evaluation=evaluation_result,
            token_usage=token_usage,
        )

    except ValueError as val_err:
        logger.error("Validation error in unified evaluation: %s", str(val_err))
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=str(val_err))
    except Exception as e:
        logger.error("Unexpected error in unified evaluation: %s", str(e))
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"An error occurred during unified evaluation: {str(e)}",
        )
